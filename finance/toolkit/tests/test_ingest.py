"""Tests for the raw IBKR price-history ingest.

Every test points FINANCE_STORE at a temporary directory so nothing touches
the real ~/.finance. The fixtures under fixtures/ are synthetic: the symbols
TESTA, TESTB and TESTFX, the exchanges TESTX, TESTY and TESTFXX, contract ids
below 1000 and prices generated by the formula each fixture states in its
``_comment`` field. Nothing here resembles a real instrument or account.
"""

from __future__ import annotations

import copy
import io
import json
import os
import shutil
import sys
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import ingest  # noqa: E402
import registry  # noqa: E402
import store  # noqa: E402

FIXTURES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures")

DELAYED_FIXTURE = os.path.join(FIXTURES, "ibkr_history_daily_delayed.json")
LIVE_FIXTURE = os.path.join(FIXTURES, "ibkr_history_daily_live.json")
FX_FIXTURE = os.path.join(FIXTURES, "ibkr_history_fx.json")

#: Synthetic ISIN with a valid check digit; not issued to any real instrument.
ISIN_TESTA = "ZZ0000TESTA1"


def load_fixture(path):
    with open(path) as handle:
        return json.load(handle)


class IngestTestCase(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="finance-ingest-test-")
        self._prev = os.environ.get("FINANCE_STORE")
        os.environ["FINANCE_STORE"] = self.tmp

    def tearDown(self):
        if self._prev is None:
            os.environ.pop("FINANCE_STORE", None)
        else:
            os.environ["FINANCE_STORE"] = self._prev
        shutil.rmtree(self.tmp, ignore_errors=True)

    def run_cli(self, argv):
        out = io.StringIO()
        err = io.StringIO()
        with redirect_stdout(out), redirect_stderr(err):
            code = ingest.main(argv)
        return code, out.getvalue(), err.getvalue()

    def write_raw(self, data, name="raw.json"):
        path = os.path.join(self.tmp, name)
        with open(path, "w") as handle:
            json.dump(data, handle)
        return path

    def store_files(self):
        base = os.path.join(self.tmp, "bars")
        found = []
        for directory, _, filenames in os.walk(base):
            for filename in filenames:
                found.append(os.path.join(directory, filename))
        return sorted(found)


class TestDelayedDaily(IngestTestCase):
    def test_sidecar_records_the_delay_and_the_venue(self):
        sidecar = ingest.ingest_ibkr_history(
            load_fixture(DELAYED_FIXTURE),
            symbol="TESTA",
            exchange="testx",
            currency="eur",
            contract_id=101,
        )
        self.assertEqual(sidecar["key"], "TESTX_TESTA")
        self.assertEqual(sidecar["source"], "ibkr")
        self.assertEqual(sidecar["interval"], "1d")
        self.assertEqual(sidecar["delayed_sec"], 900)
        self.assertEqual(sidecar["price_source"], "Last")
        self.assertEqual(sidecar["exchange"], "TESTX")
        self.assertEqual(sidecar["currency"], "EUR")
        self.assertEqual(sidecar["contract_id"], 101)
        self.assertEqual(sidecar["bar_count"], 12)
        self.assertEqual(sidecar["start"], "2026-08-03")
        self.assertEqual(sidecar["end"], "2026-08-14")
        self.assertIs(sidecar["adjusted"], False)

    def test_bars_round_trip_through_the_store(self):
        ingest.ingest_ibkr_history(
            load_fixture(DELAYED_FIXTURE),
            symbol="TESTA",
            exchange="TESTX",
            currency="EUR",
        )
        rows, meta = store.read_bars("ibkr", "TESTX_TESTA", "1d")
        self.assertEqual(len(rows), 12)
        self.assertEqual(rows[0]["date"], "2026-08-03")
        # close_i = 100 + i, open = close - 0.5, high = close + 1,
        # low = close - 1, volume = 1000 * (i + 1).
        self.assertEqual(rows[0]["close"], 100.0)
        self.assertEqual(rows[0]["open"], 99.5)
        self.assertEqual(rows[0]["high"], 101.0)
        self.assertEqual(rows[0]["low"], 99.0)
        self.assertEqual(rows[0]["volume"], 1000.0)
        self.assertEqual(rows[-1]["close"], 111.0)
        self.assertEqual(meta["bar_count"], 12)


class TestLiveDaily(IngestTestCase):
    def test_absent_delayed_key_means_zero(self):
        sidecar = ingest.ingest_ibkr_history(
            load_fixture(LIVE_FIXTURE),
            symbol="TESTB",
            exchange="TESTY",
            currency="USD",
        )
        self.assertEqual(sidecar["delayed_sec"], 0)

