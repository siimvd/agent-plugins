class TestAdjustedFlag(IngestTestCase):
    def test_default_is_false(self):
        code, out, _ = self.run_cli(
            ["ibkr-history", DELAYED_FIXTURE, "--symbol", "TESTA",
             "--exchange", "TESTX", "--currency", "EUR", "--json"]
        )
        self.assertEqual(code, 0)
        self.assertIs(json.loads(out)["adjusted"], False)

    def test_true_and_false_and_null(self):
        for text, expected in (("true", True), ("false", False), ("null", None)):
            code, out, err = self.run_cli(
                ["ibkr-history", DELAYED_FIXTURE, "--symbol", "TESTA",
                 "--exchange", "TESTX", "--currency", "EUR",
                 "--adjusted", text, "--json"]
            )
            self.assertEqual(code, 0, err)
            self.assertIs(json.loads(out)["adjusted"], expected)


class TestCli(IngestTestCase):
    def test_human_output_names_the_key_and_bar_count(self):
        code, out, err = self.run_cli(
            ["ibkr-history", DELAYED_FIXTURE, "--symbol", "TESTA",
             "--exchange", "TESTX", "--currency", "EUR", "--contract-id", "101"]
        )
        self.assertEqual(code, 0, err)
        self.assertIn("TESTX_TESTA", out)
        self.assertIn("12", out)
        self.assertIn("900", out)
        self.assertIn("Last", out)
        self.assertIn("2026-08-03", out)
        self.assertIn("2026-08-14", out)

    def test_json_output_parses_and_matches_the_sidecar_on_disk(self):
        code, out, err = self.run_cli(
            ["ibkr-history", FX_FIXTURE, "--symbol", "TESTFX",
             "--exchange", "TESTFXX", "--currency", "USD", "--json"]
        )
        self.assertEqual(code, 0, err)
        printed = json.loads(out)
        self.assertEqual(printed["key"], "TESTFXX_TESTFX")
        self.assertEqual(
            printed, store.read_meta("ibkr", "TESTFXX_TESTFX", "1d")
        )

    def test_no_subcommand_prints_help_and_fails(self):
        code, _, err = self.run_cli([])
        self.assertEqual(code, 1)
        self.assertIn("ibkr-history", err)

    def test_fixture_input_is_not_mutated(self):
        raw = load_fixture(DELAYED_FIXTURE)
        before = copy.deepcopy(raw)
        ingest.ingest_ibkr_history(
            raw, symbol="TESTA", exchange="TESTX", currency="EUR"
        )
        self.assertEqual(raw, before)


class TestFixtures(unittest.TestCase):
    """The fixtures themselves must stay synthetic and self-describing."""

    def test_every_fixture_states_its_price_formula(self):
        for path in (DELAYED_FIXTURE, LIVE_FIXTURE, FX_FIXTURE):
            data = load_fixture(path)
            self.assertIn("_comment", data, path)
            self.assertIn("close_i", data["_comment"], path)

    def test_shapes_match_the_documented_variants(self):
        delayed = load_fixture(DELAYED_FIXTURE)
        self.assertEqual(delayed["delayed"], 900)
        self.assertEqual(len(delayed["close"]), 12)

        live = load_fixture(LIVE_FIXTURE)
        self.assertNotIn("delayed", live)
        self.assertEqual(len(live["close"]), 12)

        fx = load_fixture(FX_FIXTURE)
        self.assertNotIn("volume", fx)
        self.assertEqual(fx["source"], "MidPoint")
        self.assertEqual(len(fx["close"]), 5)


class TestIntervalArgumentIsConstrained(IngestTestCase):
    """--interval is a closed set, so it cannot become a chosen filename."""

    def setUp(self):
        super().setUp()
        self.sandbox = self.tmp
        self.store_root = os.path.join(self.sandbox, "store")
        os.makedirs(self.store_root)
        os.environ["FINANCE_STORE"] = self.store_root

    def test_traversing_interval_is_refused_and_writes_nothing(self):
        raw = self.write_raw(load_fixture(DELAYED_FIXTURE))
        argv = [
            "ibkr-history",
            raw,
            "--symbol",
            "TESTA",
            "--exchange",
            "TESTX",
            "--currency",
            "EUR",
            "--interval",
            "1d/../x",
        ]
        try:
            code, _, _ = self.run_cli(argv)
        except SystemExit as exc:
            code = exc.code
        self.assertIn(code, (1, 2))
        self.assertEqual(sorted(os.listdir(self.store_root)), [])
        self.assertEqual(sorted(os.listdir(self.sandbox)), ["raw.json", "store"])

    def test_known_intervals_are_still_accepted(self):
        raw = self.write_raw(load_fixture(DELAYED_FIXTURE))
        code, _, err = self.run_cli(
            [
                "ibkr-history",
                raw,
                "--symbol",
                "TESTA",
                "--exchange",
                "TESTX",
                "--currency",
                "EUR",
                "--interval",
                "1d",
            ]
        )
        self.assertEqual(code, 0, err)


